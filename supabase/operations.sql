-- Ejecutar en el proyecto Supabase de pedidos y llamados al mesero.
-- POLÍTICAS ABIERTAS: solo desarrollo, nunca usar así en producción.

CREATE TABLE IF NOT EXISTS public.pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mesa TEXT NOT NULL,
    detalles JSONB NOT NULL,
    total NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
    estado TEXT NOT NULL DEFAULT 'Pendiente',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.waiter_calls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_number INTEGER NOT NULL CHECK (table_number > 0),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'resolved')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.pedidos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.waiter_calls ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir acceso total a pedidos" ON public.pedidos;
CREATE POLICY "Permitir acceso total a pedidos" ON public.pedidos
    FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir acceso total a waiter_calls" ON public.waiter_calls;
CREATE POLICY "Permitir acceso total a waiter_calls" ON public.waiter_calls
    FOR ALL USING (true) WITH CHECK (true);

-- La app escucha cambios en ambas tablas operativas.
DO $$
DECLARE
    target_table TEXT;
BEGIN
    FOREACH target_table IN ARRAY ARRAY['pedidos', 'waiter_calls'] LOOP
        IF NOT EXISTS (
            SELECT 1 FROM pg_publication_tables
            WHERE pubname = 'supabase_realtime'
              AND schemaname = 'public'
              AND tablename = target_table
        ) THEN
            EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', target_table);
        END IF;
    END LOOP;
END $$;
