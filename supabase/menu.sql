CREATE TABLE IF NOT EXISTS public.platos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    precio NUMERIC(12, 2) NOT NULL CHECK (precio > 0),
    categoria TEXT NOT NULL,
    imagen_url TEXT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT NOT NULL,
    table_number INTEGER NOT NULL CHECK (table_number > 0),
    item_id TEXT NOT NULL,
    item_name TEXT NOT NULL,
    stars INTEGER NOT NULL CHECK (stars BETWEEN 1 AND 5),
    feedback TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.platos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ratings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir acceso total a platos" ON public.platos;
CREATE POLICY "Permitir acceso total a platos" ON public.platos
    FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir acceso total a ratings" ON public.ratings;
CREATE POLICY "Permitir acceso total a ratings" ON public.ratings
    FOR ALL USING (true) WITH CHECK (true);
