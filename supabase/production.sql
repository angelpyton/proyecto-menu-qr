-- este archivo elimina las políticas de desarrollo conocidas.

CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;
ALTER EXTENSION pgcrypto SET SCHEMA extensions;

CREATE TABLE IF NOT EXISTS public.platos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    precio NUMERIC(12, 2) NOT NULL CHECK (precio > 0),
    categoria TEXT NOT NULL,
    imagen_url TEXT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT NOT NULL,
    table_number INTEGER NOT NULL CHECK (table_number BETWEEN 1 AND 100),
    item_id TEXT NOT NULL,
    item_name TEXT NOT NULL,
    stars INTEGER NOT NULL CHECK (stars BETWEEN 1 AND 5),
    feedback TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mesa TEXT NOT NULL,
    detalles JSONB NOT NULL,
    total NUMERIC(12, 2) NOT NULL CHECK (total > 0),
    estado TEXT NOT NULL DEFAULT 'Pendiente'
        CHECK (estado IN ('Pendiente', 'En preparación', 'Listo', 'Entregado')),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    tracking_token_hash TEXT
);

ALTER TABLE public.pedidos
    ADD COLUMN IF NOT EXISTS tracking_token_hash TEXT;

CREATE TABLE IF NOT EXISTS public.waiter_calls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_number INTEGER NOT NULL CHECK (table_number BETWEEN 1 AND 100),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'resolved')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.platos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ratings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pedidos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.waiter_calls ENABLE ROW LEVEL SECURITY;

-- Remove every existing policy so an older permissive policy cannot override these rules.
DO $$
DECLARE policy_row RECORD;
BEGIN
    FOR policy_row IN
        SELECT schemaname, tablename, policyname
        FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename IN ('platos', 'ratings', 'pedidos', 'waiter_calls')
    LOOP
        EXECUTE format('DROP POLICY %I ON %I.%I', policy_row.policyname, policy_row.schemaname, policy_row.tablename);
    END LOOP;
END $$;

DROP POLICY IF EXISTS "menu_read_public" ON public.platos;
CREATE POLICY "menu_read_public" ON public.platos
    FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "staff_manage_menu" ON public.platos;
CREATE POLICY "staff_manage_menu" ON public.platos
    FOR ALL TO authenticated
    USING ((auth.jwt() -> 'app_metadata' ->> 'role') = 'staff')
    WITH CHECK ((auth.jwt() -> 'app_metadata' ->> 'role') = 'staff');

DROP POLICY IF EXISTS "ratings_read_public" ON public.ratings;
CREATE POLICY "ratings_read_public" ON public.ratings
    FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "ratings_insert_public" ON public.ratings;
CREATE POLICY "ratings_insert_public" ON public.ratings
    FOR INSERT TO anon, authenticated
    WITH CHECK (stars BETWEEN 1 AND 5 AND length(feedback) <= 120);

DROP POLICY IF EXISTS "staff_read_orders" ON public.pedidos;
CREATE POLICY "staff_read_orders" ON public.pedidos
    FOR SELECT TO authenticated
    USING ((auth.jwt() -> 'app_metadata' ->> 'role') = 'staff');
DROP POLICY IF EXISTS "staff_update_orders" ON public.pedidos;
CREATE POLICY "staff_update_orders" ON public.pedidos
    FOR UPDATE TO authenticated
    USING ((auth.jwt() -> 'app_metadata' ->> 'role') = 'staff')
    WITH CHECK ((auth.jwt() -> 'app_metadata' ->> 'role') = 'staff');

DROP POLICY IF EXISTS "waiter_call_insert_public" ON public.waiter_calls;
CREATE POLICY "waiter_call_insert_public" ON public.waiter_calls
    FOR INSERT TO anon, authenticated WITH CHECK (status = 'pending');
DROP POLICY IF EXISTS "staff_read_waiter_calls" ON public.waiter_calls;
CREATE POLICY "staff_read_waiter_calls" ON public.waiter_calls
    FOR SELECT TO authenticated
    USING ((auth.jwt() -> 'app_metadata' ->> 'role') = 'staff');
DROP POLICY IF EXISTS "staff_update_waiter_calls" ON public.waiter_calls;
CREATE POLICY "staff_update_waiter_calls" ON public.waiter_calls
    FOR UPDATE TO authenticated
    USING ((auth.jwt() -> 'app_metadata' ->> 'role') = 'staff')
    WITH CHECK ((auth.jwt() -> 'app_metadata' ->> 'role') = 'staff');

REVOKE ALL ON public.platos, public.ratings, public.pedidos, public.waiter_calls FROM anon, authenticated;
GRANT SELECT ON public.platos, public.ratings TO anon, authenticated;
GRANT INSERT ON public.ratings, public.waiter_calls TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.platos TO authenticated;
GRANT SELECT ON public.pedidos, public.waiter_calls TO authenticated;
GRANT UPDATE (estado) ON public.pedidos TO authenticated;
GRANT UPDATE (status) ON public.waiter_calls TO authenticated;
DO $$
DECLARE sequence_row RECORD;
BEGIN
    FOR sequence_row IN
        SELECT pg_get_serial_sequence(format('public.%I', table_name), 'id') AS sequence_name
        FROM (VALUES ('ratings'), ('waiter_calls')) AS tables(table_name)
    LOOP
        IF sequence_row.sequence_name IS NOT NULL THEN
            EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO anon, authenticated', sequence_row.sequence_name);
        END IF;
    END LOOP;
END $$;

CREATE OR REPLACE FUNCTION public.create_order(
    p_table INTEGER,
    p_items JSONB,
    p_instructions TEXT,
    p_tracking_token UUID
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions, pg_temp
AS $$
DECLARE
    v_line JSONB;
    v_product RECORD;
    v_qty INTEGER;
    v_total NUMERIC(12, 2) := 0;
    v_items JSONB := '[]'::JSONB;
    v_details JSONB;
    v_order_id BIGINT;
    v_instructions TEXT := COALESCE(BTRIM(p_instructions), '');
BEGIN
    IF p_table IS NULL OR p_table NOT BETWEEN 1 AND 100 THEN
        RAISE EXCEPTION 'Número de mesa inválido';
    END IF;
    IF p_tracking_token IS NULL THEN
        RAISE EXCEPTION 'Token de seguimiento requerido';
    END IF;
    IF p_items IS NULL OR jsonb_typeof(p_items) IS DISTINCT FROM 'array' THEN
        RAISE EXCEPTION 'El pedido debe ser una lista de productos';
    END IF;
    IF jsonb_array_length(p_items) NOT BETWEEN 1 AND 50 THEN
        RAISE EXCEPTION 'El pedido debe incluir entre 1 y 50 productos';
    END IF;
    IF length(v_instructions) > 500 THEN
        RAISE EXCEPTION 'Las instrucciones superan el límite permitido';
    END IF;

    FOR v_line IN SELECT value FROM jsonb_array_elements(p_items)
    LOOP
        IF COALESCE(v_line ->> 'id', '') !~ '^[0-9]{1,18}$'
           OR COALESCE(v_line ->> 'qty', '') !~ '^[0-9]{1,2}$' THEN
            RAISE EXCEPTION 'Producto o cantidad inválidos';
        END IF;

        v_qty := (v_line ->> 'qty')::INTEGER;
        IF v_qty NOT BETWEEN 1 AND 99 THEN
            RAISE EXCEPTION 'Cantidad de producto fuera de rango';
        END IF;

        SELECT id, nombre, precio, categoria, imagen_url
          INTO v_product
          FROM public.platos
         WHERE id = (v_line ->> 'id')::BIGINT;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Uno de los productos ya no está disponible';
        END IF;

        v_total := v_total + (v_product.precio * v_qty);
        v_items := v_items || jsonb_build_array(jsonb_build_object(
            'id', v_product.id,
            'name', v_product.nombre,
            'price', v_product.precio,
            'category', v_product.categoria,
            'image', CASE WHEN v_product.imagen_url LIKE 'data:%' THEN '' ELSE COALESCE(v_product.imagen_url, '') END,
            'qty', v_qty
        ));
    END LOOP;

    v_details := jsonb_build_object('items', v_items, 'instructions', v_instructions);
    INSERT INTO public.pedidos (mesa, detalles, total, estado, tracking_token_hash)
    VALUES (
        p_table::TEXT,
        v_details,
        v_total,
        'Pendiente',
        encode(extensions.digest(p_tracking_token::TEXT, 'sha256'), 'hex')
    )
    RETURNING id INTO v_order_id;

    RETURN jsonb_build_object('id', v_order_id, 'total', v_total, 'details', v_details);
END;
$$;

CREATE OR REPLACE FUNCTION public.get_order_status(p_order_id BIGINT, p_tracking_token UUID)
RETURNS JSONB
LANGUAGE SQL
SECURITY DEFINER
SET search_path = public, extensions, pg_temp
AS $$
    SELECT jsonb_build_object('id', id, 'status', estado)
      FROM public.pedidos
     WHERE id = p_order_id
       AND tracking_token_hash = encode(extensions.digest(p_tracking_token::TEXT, 'sha256'), 'hex');
$$;

REVOKE ALL ON FUNCTION public.create_order(INTEGER, JSONB, TEXT, UUID) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.get_order_status(BIGINT, UUID) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_order(INTEGER, JSONB, TEXT, UUID) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_order_status(BIGINT, UUID) TO anon, authenticated;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'pedidos'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.pedidos;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'waiter_calls'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.waiter_calls;
    END IF;
END $$;
